import { existsSync, readFileSync } from "node:fs";
import { registerHooks } from "node:module";
import { spawnSync } from "node:child_process";
registerHooks({ resolve(specifier, context, next) {
 if (specifier.startsWith(".") && context.parentURL && !/\.[cm]?[jt]sx?$/.test(specifier)) {
  const candidate = new URL(specifier + ".ts", context.parentURL);
  if (existsSync(candidate)) return next(candidate.href, context);
 }
 return next(specifier, context);
} });
const { eventGroups } = await import("../app/EventsData.ts");
const { exclusiveChoiceGroups } = await import("../app/EventConditionLogic.ts");
const rows = []; let checked = 0; const unavailable = [], mismatched = [];
for (const record of eventGroups.flatMap(group => group.records)) {
 if (!existsSync(record.sourceFile)) { unavailable.push(record.eventId); continue; }
 const source = JSON.parse(readFileSync(record.sourceFile, "utf8").replace(/^\uFEFF/, ""));
 if (source.id !== record.eventId || !source.choices || source.choices.length !== record.entry.eventOptions?.length || source.conditional !== record.condition) {
  mismatched.push(record.eventId); continue;
 }
 checked++;
 const conditions = source.choices.map(choice => choice.condition?.trim() ?? "");
 const groups = exclusiveChoiceGroups(conditions, record.condition);
 if (!groups.length) continue;
 rows.push({ id: record.eventId, context: record.condition, choices: source.choices.map((choice, index) => ({
  name: record.entry.eventOptions[index].name, condition: conditions[index], display: record.entry.eventOptions[index].condition ?? "",
 })), groups });
 console.log(source.name + " | " + record.eventId + " | groups " + groups.map(group => group.map(index => index + 1).join(",")).join(" / "));
}
console.log(JSON.stringify({ checked, unavailable, mismatched, conditionalEvents: rows.length, deterministic: rows.filter(row => row.groups.every(group => group.length === 1)).length }));
if (process.argv.includes("--update")) {
 const path = "app/EventChoiceSourceAudit.ts";
 const content = "// Generated by scripts/audit-event-choice-conditions.mjs --update.\n// Guards include the original eligibility, option names, and translated conditions.\nexport const eventChoiceSourceAudit = " + JSON.stringify(rows, null, 2) + ";\n";
 const prior = existsSync(path) ? readFileSync(path, "utf8") : "";
 const patch = "*** Begin Patch\n" + (prior ? "*** Update File: " + path + "\n@@\n" + prior.trimEnd().split(/\r?\n/).map(line => "-" + line).join("\n") + "\n" : "*** Add File: " + path + "\n") + content.trimEnd().split("\n").map(line => "+" + line).join("\n") + "\n*** End Patch";
 const result = spawnSync("C:/Users/zi123/AppData/Local/OpenAI/Codex/bin/c6fe824d725f02d7/codex.exe", ["--codex-run-as-apply-patch", patch], { encoding: "utf8" });
 console.log(result.stdout); if (result.status) { console.error(result.stderr); process.exit(result.status); }
}
